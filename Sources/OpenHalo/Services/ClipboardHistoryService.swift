import Foundation
import AppKit
import Combine

@MainActor
public final class ClipboardHistoryService: ObservableObject {
    @Published public var items: [ClipboardItem] = []
    @Published public var searchQuery: String = ""
    @Published public var selectedFilter: ClipboardItemType = .all
    @Published public var lastCopiedToast: String? = nil

    private var lastChangeCount: Int = 0
    private var pollTimer: Timer?
    private let maxItems: Int = 50

    public init() {
        self.lastChangeCount = NSPasteboard.general.changeCount
        startMonitoring()
    }

    public func startMonitoring() {
        pollTimer?.invalidate()
        // 1.5s polling with 0.5s timer coalescing tolerance for low idle CPU
        pollTimer = Timer.scheduledTimer(withTimeInterval: 1.5, repeats: true) { [weak self] _ in
            Task { @MainActor [weak self] in
                self?.checkForNewClip()
            }
        }
        pollTimer?.tolerance = 0.5
    }

    public func stopMonitoring() {
        pollTimer?.invalidate()
        pollTimer = nil
    }

    public func checkForNewClip() {
        let pasteboard = NSPasteboard.general
        let currentChangeCount = pasteboard.changeCount

        guard currentChangeCount != lastChangeCount else { return }
        lastChangeCount = currentChangeCount

        // Security Guard: Ignore passwords from 1Password, Bitwarden, Keychain, MacPass, KeePassXC, etc.
        let concealedTypes: [NSPasteboard.PasteboardType] = [
            NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
            NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
            NSPasteboard.PasteboardType("com.agilebits.onepassword"),
            NSPasteboard.PasteboardType("com.bitwarden.desktop"),
            NSPasteboard.PasteboardType("keepassxc"),
            NSPasteboard.PasteboardType("com.lastpass.LastPass"),
            NSPasteboard.PasteboardType("de.bernhard-baehr.MacPass"),
            NSPasteboard.PasteboardType("com.apple.security.SecItem")
        ]

        if let types = pasteboard.types, types.contains(where: { concealedTypes.contains($0) }) {
            return
        }

        // 1. Check for Image / Screenshot Data
        if let image = NSImage(pasteboard: pasteboard),
           let tiffData = image.tiffRepresentation,
           let bitmap = NSBitmapImageRep(data: tiffData),
           let pngData = bitmap.representation(using: .png, properties: [:]) {

            // Prevent duplicate consecutive image copies
            if let first = items.first, first.type == .image, first.imageData == pngData {
                return
            }

            let dimensionStr = "\(Int(image.size.width)) × \(Int(image.size.height))"
            let newItem = ClipboardItem(
                content: "Screenshot • \(dimensionStr)",
                type: .image,
                imageData: pngData
            )
            insertNewItem(newItem)
            return
        }

        // 2. Check for Text / Links / Code / Colors
        if let text = pasteboard.string(forType: .string), !text.isEmpty {
            if let first = items.first, first.content == text {
                return
            }

            let newItem = ClipboardItem(content: text)
            insertNewItem(newItem)
            return
        }
    }

    private func insertNewItem(_ item: ClipboardItem) {
        // Keep pinned items at top
        let pinned = items.filter { $0.isPinned }
        var unpinned = items.filter { !$0.isPinned }

        unpinned.insert(item, at: 0)
        if unpinned.count > maxItems {
            unpinned = Array(unpinned.prefix(maxItems))
        }

        self.items = pinned + unpinned
    }

    public func copyToClipboard(_ item: ClipboardItem) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()

        if item.type == .image, let data = item.imageData {
            pasteboard.setData(data, forType: .png)
            if let image = NSImage(data: data) {
                pasteboard.writeObjects([image])
            }
            showToast("Image copied to clipboard!")
        } else {
            pasteboard.setString(item.content, forType: .string)
            showToast("Copied to clipboard!")
        }

        self.lastChangeCount = pasteboard.changeCount
    }

    public func togglePin(id: UUID) {
        if let idx = items.firstIndex(where: { $0.id == id }) {
            items[idx].isPinned.toggle()
            // Re-sort: pinned first, then by timestamp descending
            items.sort { a, b in
                if a.isPinned != b.isPinned {
                    return a.isPinned && !b.isPinned
                }
                return a.timestamp > b.timestamp
            }
        }
    }

    public func deleteItem(id: UUID) {
        items.removeAll { $0.id == id }
    }

    public func clearAll() {
        // Keep pinned items when clearing
        items.removeAll { !$0.isPinned }
        showToast("Cleared non-pinned history")
    }

    private func showToast(_ message: String) {
        self.lastCopiedToast = message
        DispatchQueue.main.asyncAfter(deadline: .now() + 1.5) { [weak self] in
            if self?.lastCopiedToast == message {
                self?.lastCopiedToast = nil
            }
        }
    }

    public var filteredItems: [ClipboardItem] {
        var result = items

        // Filter by category
        if selectedFilter == .pinned {
            result = result.filter { $0.isPinned }
        } else if selectedFilter != .all {
            result = result.filter { $0.type == selectedFilter }
        }

        // Filter by search query
        let query = searchQuery.trimmingCharacters(in: .whitespacesAndNewlines)
        if !query.isEmpty {
            result = result.filter { $0.content.localizedCaseInsensitiveContains(query) }
        }

        return result
    }
}
